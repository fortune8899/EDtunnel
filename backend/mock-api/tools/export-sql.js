const fs = require('fs');
const path = require('path');

const inFile = process.env.MOCK_DB_FILE || path.join(__dirname, '..', 'data', 'mock-db.json');
const outFile = process.env.OUT_SQL_FILE || path.join(__dirname, '..', 'data', 'mock-export.sql');
const userId = Number(process.env.EXPORT_USER_ID || 1);

function esc(v) {
  if (v === null || v === undefined) return 'NULL';
  return `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
}

if (!fs.existsSync(inFile)) {
  console.error(`Input file not found: ${inFile}`);
  process.exit(1);
}

const db = JSON.parse(fs.readFileSync(inFile, 'utf8'));
const records = Array.isArray(db.records) ? db.records : [];

const lines = [];
lines.push('-- Auto generated by backend/mock-api/tools/export-sql.js');
lines.push(`-- Source: ${inFile}`);
lines.push(`-- Record count: ${records.length}`);
lines.push('BEGIN;');

for (const r of records) {
  const row = [
    userId,
    esc(r.eval_date),
    esc(r.start_time),
    esc(r.location),
    esc(r.project_name),
    esc(r.source_platform),
    Number(r.role_in_group || 2),
    esc(r.profession_code),
    esc(r.custom_profession),
    esc(r.summary_content),
    esc(r.risk_notes),
    Number(r.expected_fee || 0),
    r.actual_paid_amount == null ? 'NULL' : Number(r.actual_paid_amount),
    esc(r.paid_date),
    Number(r.settlement_status || 0),
    esc(r.created_at || new Date().toISOString().slice(0, 19).replace('T', ' ')),
    esc(r.updated_at || new Date().toISOString().slice(0, 19).replace('T', ' ')),
  ];

  lines.push(
    'INSERT INTO eval_records (user_id, eval_date, start_time, location, project_name, source_platform, role_in_group, profession_code, custom_profession, summary_content, risk_notes, expected_fee, actual_paid_amount, paid_date, settlement_status, created_at, updated_at) VALUES (' +
      row.join(', ') +
      ');'
  );
}

lines.push('COMMIT;');

fs.writeFileSync(outFile, lines.join('\n') + '\n', 'utf8');
console.log(`SQL exported: ${outFile}`);
console.log(`Rows: ${records.length}`);
